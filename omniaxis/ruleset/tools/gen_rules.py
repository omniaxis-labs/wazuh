#!/usr/bin/env python3
"""Generate omniaxis/ruleset/rules/0900-omniaxis_scdc_rules.xml.

Wazuh puts only the groups of the final matching rule on an alert, so each
product needs its own rule per severity to carry both the product group and the
severity group. Writing 4 x N rules by hand invites drift; this script is the
source of truth and `--check` fails CI when the XML is out of date.

Usage:
    python3 gen_rules.py            # rewrite the rules file
    python3 gen_rules.py --check    # exit 1 if the file differs
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
PRODUCTS_FILE = HERE / "products.json"
RULES_FILE = HERE.parent / "rules" / "0900-omniaxis_scdc_rules.xml"

# Contract severity -> Wazuh level. SEV1 >= 13, SEV2 10-12, SEV3 7-9, SEV4 3-6.
SEVERITY_LEVEL = {"sev1": 13, "sev2": 10, "sev3": 7, "sev4": 3}

# Repeats of the same dedupe_key inside the window raise the alert one band.
# Wazuh fires a frequency rule on exactly the Nth match, then counts afresh.
ESCALATE_COUNT = 5
ESCALATE_WINDOW_S = 600

# Where verified events can come from. "API-Webhook" is the location analysisd
# gives to POST /events; the file is the relay's localfile fallback. Agent
# events always carry an "(agent) ip->" prefix, so an agent cannot spoof these.
INTAKE_LOCATION = r"^API-Webhook$|^/var/log/omniaxis-scdc/intake.log$"
RELAY_LOCATION = r"^/var/log/omniaxis-scdc/relay.log$"

PRODUCT_BASE = 100110
PRODUCT_STRIDE = 10
PRODUCT_MAX_ID = 100799
NAME_RE = re.compile(r"^[a-z][a-z0-9-]{1,30}$")


def product_rules(index: int, product: str) -> str:
    base = PRODUCT_BASE + PRODUCT_STRIDE * index
    if base + 9 > PRODUCT_MAX_ID:
        raise SystemExit(f"too many products: {product} would use ids past {PRODUCT_MAX_ID}")
    title = product.capitalize()
    out = [f"""
  <!-- {title}: rule ids {base}-{base + 9} -->
  <rule id="{base}" level="5">
    <if_sid>100101</if_sid>
    <field name="source">^{product}$</field>
    <description>SCDC {title}: event with an unrecognised severity: $(type)</description>
    <group>scdc,{product},scdc_bad_severity,</group>
  </rule>
"""]
    for offset, (sev, level) in enumerate(SEVERITY_LEVEL.items(), start=1):
        out.append(f"""
  <rule id="{base + offset}" level="{level}">
    <if_sid>{base}</if_sid>
    <field name="severity">^{sev}$</field>
    <description>{title} {sev.upper()}: $(title)</description>
    <group>scdc,{product},scdc_{sev},</group>
  </rule>
""")
    # Escalation: SEV3 repeats -> SEV2 band; SEV2 repeats -> SEV1 band.
    for offset, (src_off, src, dst, level) in enumerate(
        [(3, "sev3", "sev2", SEVERITY_LEVEL["sev2"]), (2, "sev2", "sev1", SEVERITY_LEVEL["sev1"])], start=5
    ):
        out.append(f"""
  <rule id="{base + offset}" level="{level}" frequency="{ESCALATE_COUNT}" timeframe="{ESCALATE_WINDOW_S}">
    <if_matched_sid>{base + src_off}</if_matched_sid>
    <same_field>dedupe_key</same_field>
    <description>{title} {dst.upper()} (escalated): {src.upper()} repeated {ESCALATE_COUNT} times in {ESCALATE_WINDOW_S // 60} minutes: $(title)</description>
    <group>scdc,{product},scdc_{dst},scdc_escalated,</group>
  </rule>
""")
    return "".join(out)


def render() -> str:
    products = json.loads(PRODUCTS_FILE.read_text())["products"]
    if len(set(products)) != len(products):
        raise SystemExit("duplicate product in products.json")
    for p in products:
        if not NAME_RE.match(p):
            raise SystemExit(f"bad product name: {p!r}")
    body = "".join(product_rules(i, p) for i, p in enumerate(products))
    known = "|".join(f"^{p}$" for p in products)
    return f"""<!--
  OmniAxis Labs SCDC rules. GENERATED by omniaxis/ruleset/tools/gen_rules.py
  from products.json. Do not edit by hand; run the script.

  Severity bands: SEV1 = level 13+, SEV2 = 10-12, SEV3 = 7-9, SEV4 = 3-6.
  Every alert carries data.product (set by the relay from the signing key).
  Rule ids: 100100-100104 intake base, 100110-100799 products, 100900-100919 relay.
-->

<group name="omniaxis_labs,">

  <!-- Any line carrying the SCDC prefix. -->
  <rule id="100100" level="0">
    <decoded_as>omniaxis-scdc</decoded_as>
    <description>SCDC contract line</description>
  </rule>

  <!-- A verified contract event: it came through the intake relay. -->
  <rule id="100101" level="0">
    <if_sid>100100</if_sid>
    <location>{INTAKE_LOCATION}</location>
    <field name="specversion">^scdc/1$</field>
    <description>SCDC contract event</description>
  </rule>

  <!-- A contract-shaped line from anywhere else. Level 12 sorts it before
       100101, so it must exclude the relay locations itself. -->
  <rule id="100102" level="12">
    <if_sid>100100</if_sid>
    <location negate="yes">{INTAKE_LOCATION}</location>
    <description>SCDC event seen outside the intake relay (possible forgery) at $(location)</description>
    <group>scdc,scdc_forged,scdc_sev2,</group>
  </rule>

  <rule id="100104" level="12">
    <if_sid>100100</if_sid>
    <location>{INTAKE_LOCATION}</location>
    <field name="specversion" negate="yes">^scdc/1$</field>
    <description>SCDC event with an unsupported specversion: $(specversion)</description>
    <group>scdc,scdc_bad_version,scdc_sev2,</group>
  </rule>
{body}
  <!-- Wazuh tries sibling rules highest level first, so this one must exclude
       the listed products explicitly rather than rely on order. -->
  <rule id="100103" level="10">
    <if_sid>100101</if_sid>
    <field name="source" negate="yes">{known}</field>
    <description>SCDC event from a product with no rules: $(source)</description>
    <group>scdc,scdc_unknown_product,scdc_sev2,</group>
  </rule>

  <!-- Intake relay health and refusals. -->
  <rule id="100900" level="0">
    <decoded_as>omniaxis-scdc-relay</decoded_as>
    <location>{RELAY_LOCATION}</location>
    <description>SCDC intake relay log</description>
  </rule>

  <rule id="100901" level="4">
    <if_sid>100900</if_sid>
    <field name="event">^refused$</field>
    <description>SCDC intake refused a request: $(reason)</description>
    <group>scdc,scdc_relay,</group>
  </rule>

  <rule id="100902" level="10">
    <if_sid>100901</if_sid>
    <field name="reason">^source_mismatch$</field>
    <description>SCDC intake: a valid product key signed an event for another product ($(claimed_source))</description>
    <group>scdc,scdc_relay,scdc_sev2,</group>
  </rule>

  <rule id="100903" level="10" frequency="20" timeframe="120">
    <if_matched_sid>100901</if_matched_sid>
    <same_srcip />
    <description>SCDC intake: burst of refused requests from $(srcip)</description>
    <group>scdc,scdc_relay,scdc_sev2,</group>
  </rule>

  <rule id="100904" level="10">
    <if_sid>100900</if_sid>
    <field name="event">^sink_failed$</field>
    <description>SCDC intake relay could not hand events to Wazuh: $(reason)</description>
    <group>scdc,scdc_relay,scdc_sev2,</group>
  </rule>

  <rule id="100905" level="3">
    <if_sid>100900</if_sid>
    <field name="event">^started$</field>
    <description>SCDC intake relay started</description>
    <group>scdc,scdc_relay,</group>
  </rule>

</group>
"""


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = RULES_FILE.read_text() if RULES_FILE.exists() else ""
        if current != text:
            print(f"{RULES_FILE} is out of date; run gen_rules.py", file=sys.stderr)
            return 1
        print("rules file is up to date")
        return 0
    RULES_FILE.write_text(text)
    print(f"wrote {RULES_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
